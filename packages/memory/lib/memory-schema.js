const SCHEMA_VERSION = 1

function storageFor(dimensions) {
  return dimensions < 2000 ? 'vector' : 'halfvec'
}

function storageType(dimensions) {
  return storageFor(dimensions) + '(' + String(dimensions) + ')'
}

function indexExpression(dimensions) {
  if (dimensions < 2000) return 'embedding vector_cosine_ops'
  if (dimensions <= 4000) return 'embedding halfvec_cosine_ops'
  return '(subvector(embedding, 1, 4000)::halfvec(4000)) halfvec_cosine_ops'
}

function indexStrategy(dimensions) {
  if (dimensions < 2000) return 'vector_full_hnsw'
  if (dimensions <= 4000) return 'halfvec_full_hnsw'
  return 'halfvec_prefix_4000_hnsw'
}

export function schemaPlan(dimensions) {
  return {
    version: SCHEMA_VERSION,
    dimensions,
    storage: storageFor(dimensions),
    storageType: storageType(dimensions),
    index: indexStrategy(dimensions),
    indexExpression: indexExpression(dimensions),
  }
}

function buildSchemaSql(dimensions) {
  const plan = schemaPlan(dimensions)
  const storage = plan.storageType
  const index = plan.indexExpression
  const strategy = plan.index
  return `
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE SCHEMA IF NOT EXISTS memory;

CREATE TABLE IF NOT EXISTS memory.memory_entities (
  seq bigint GENERATED BY DEFAULT AS IDENTITY,
  id text PRIMARY KEY,
  name text NOT NULL,
  created_at bigint NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_memory_entities_seq ON memory.memory_entities (seq);

CREATE TABLE IF NOT EXISTS memory.memory_entries (
  seq bigint GENERATED BY DEFAULT AS IDENTITY,
  id text PRIMARY KEY,
  template text NOT NULL,
  type text NOT NULL CHECK (type IN ('short', 'long', 'persona')),
  scope text NOT NULL CHECK (scope <> ''),
  source text,
  depth integer NOT NULL,
  created_at bigint NOT NULL,
  origin_msg_ids text,
  last_access bigint NOT NULL DEFAULT 0,
  c_h5m double precision NOT NULL DEFAULT 0,
  c_1h double precision NOT NULL DEFAULT 0,
  c_24h double precision NOT NULL DEFAULT 0,
  c_7d double precision NOT NULL DEFAULT 0,
  total_access integer NOT NULL DEFAULT 0,
  counters_settled_at bigint NOT NULL DEFAULT 0,
  text_revision integer NOT NULL DEFAULT 1,
  vec_revision integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_memory_entries_seq ON memory.memory_entries (seq);

CREATE TABLE IF NOT EXISTS memory.memory_entry_refs (
  memory_id text NOT NULL REFERENCES memory.memory_entries(id) ON DELETE CASCADE,
  ord integer NOT NULL,
  ref_kind text NOT NULL CHECK (ref_kind IN ('e', 'm')),
  ref_id text,
  PRIMARY KEY (memory_id, ord)
);

CREATE TABLE IF NOT EXISTS memory.memory_state (
  key text PRIMARY KEY,
  value_json text NOT NULL
);

DO $$
BEGIN
  IF to_regclass('memory.memory_entries_vec') IS NOT NULL THEN
    IF NOT EXISTS (
      SELECT 1 FROM pg_attribute a
      JOIN pg_class c ON c.oid = a.attrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = 'memory' AND c.relname = 'memory_entries_vec'
        AND a.attname = 'embedding' AND a.attnum > 0 AND NOT a.attisdropped
        AND format_type(a.atttypid, a.atttypmod) IN ('vector', 'halfvec')
    ) THEN
      DROP TABLE memory.memory_entries_vec;
    END IF;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS memory.memory_entries_vec (
  memory_id text PRIMARY KEY REFERENCES memory.memory_entries(id) ON DELETE CASCADE,
  type text NOT NULL,
  embedding ${storage} NOT NULL
);

CREATE TABLE IF NOT EXISTS memory.schema_version (
  version integer PRIMARY KEY,
  embedding_dimensions integer NOT NULL,
  embedding_storage text NOT NULL,
  embedding_index text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS memory.schema_migrations (
  id bigserial PRIMARY KEY,
  from_version integer NOT NULL,
  to_version integer NOT NULL,
  from_dimensions integer NOT NULL,
  to_dimensions integer NOT NULL,
  from_storage text NOT NULL,
  to_storage text NOT NULL,
  to_index text NOT NULL,
  status text NOT NULL,
  total_entries integer NOT NULL DEFAULT 0,
  processed_entries integer NOT NULL DEFAULT 0,
  last_memory_id text,
  backup_table text,
  error text,
  started_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz
);

ALTER TABLE memory.schema_migrations ADD COLUMN IF NOT EXISTS backup_table text;

CREATE INDEX IF NOT EXISTS idx_memory_entries_last ON memory.memory_entries (last_access);
CREATE INDEX IF NOT EXISTS idx_memory_entries_type_last ON memory.memory_entries (type, last_access);
CREATE INDEX IF NOT EXISTS idx_memory_entries_pending_embed ON memory.memory_entries (id) WHERE vec_revision < text_revision;
CREATE INDEX IF NOT EXISTS idx_memory_entries_template_trgm ON memory.memory_entries USING gin (template gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_memory_entry_refs_ref ON memory.memory_entry_refs (ref_id);
CREATE INDEX IF NOT EXISTS idx_memory_entries_vec_type ON memory.memory_entries_vec (type);
CREATE INDEX IF NOT EXISTS idx_memory_entries_vec_hnsw ON memory.memory_entries_vec USING hnsw (${index});
CREATE INDEX IF NOT EXISTS idx_schema_migrations_status ON memory.schema_migrations (status, id DESC);

INSERT INTO memory.schema_version (version, embedding_dimensions, embedding_storage, embedding_index)
VALUES (${SCHEMA_VERSION}, ${dimensions}, '${storageFor(dimensions)}', '${strategy}')
ON CONFLICT (version) DO NOTHING;

GRANT USAGE ON SCHEMA memory TO claybot_memory, claybot_core, claybot_service;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA memory TO claybot_memory;
GRANT SELECT ON ALL TABLES IN SCHEMA memory TO claybot_core, claybot_service;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA memory TO claybot_memory;
ALTER DEFAULT PRIVILEGES IN SCHEMA memory GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO claybot_memory;
ALTER DEFAULT PRIVILEGES IN SCHEMA memory GRANT SELECT ON TABLES TO claybot_core, claybot_service;
`
}

export class MemorySchema {
  constructor(db, config) {
    this.db = db
    this.config = config
    this.lastError = null
  }

  expected() {
    const dimensions = this.config.read().embedding.dimensions
    return schemaPlan(dimensions)
  }

  async rows(sql) {
    const result = await this.db.query('admin', sql)
    return (result.results && result.results[0] && result.results[0].rows) || []
  }

  async status() {
    const expected = this.expected()
    const dbStatus = await this.db.status()
    if (!dbStatus.installed || !dbStatus.running) {
      return { installed: false, schemaMissing: true, needsMigration: false, database: dbStatus, expected, migrations: [] }
    }
    try {
      const registered = await this.rows("SELECT to_regclass('memory.schema_version') AS reg")
      if (!registered.length || registered[0].reg === null) {
        return { installed: false, schemaMissing: true, needsMigration: false, database: dbStatus, expected, migrations: [] }
      }
      const versions = await this.rows('SELECT version, embedding_dimensions, embedding_storage, embedding_index, applied_at FROM memory.schema_version ORDER BY version DESC LIMIT 1')
      const tables = await this.rows("SELECT count(*)::int AS count FROM pg_tables WHERE schemaname = 'memory'")
      const migrationTable = await this.rows("SELECT to_regclass('memory.schema_migrations') AS reg")
      const migrations = migrationTable.length && migrationTable[0].reg !== null
        ? await this.rows('SELECT id, from_version, to_version, from_dimensions, to_dimensions, from_storage, to_storage, to_index, status, total_entries, processed_entries, last_memory_id, error, started_at, updated_at, finished_at FROM memory.schema_migrations ORDER BY id DESC LIMIT 20')
        : []
      const active = migrations.find((row) => ['pending', 'running', 'swapping'].includes(row.status)) || null
      const version = versions.length ? versions[0] : null
      return {
        installed: true,
        schemaMissing: false,
        database: dbStatus,
        expected,
        version: version ? version.version : null,
        dimensions: version ? version.embedding_dimensions : null,
        storage: version ? version.embedding_storage : null,
        index: version ? version.embedding_index : null,
        appliedAt: version ? version.applied_at : null,
        tables: tables.length ? tables[0].count : 0,
        needsMigration: Boolean(version && Number(version.embedding_dimensions) !== expected.dimensions),
        migration: active,
        migrations,
      }
    } catch (error) {
      this.lastError = error instanceof Error ? error.message : String(error)
      return { installed: false, schemaMissing: true, needsMigration: false, database: dbStatus, expected, migrations: [], error: this.lastError }
    }
  }

  async ensure() {
    const expected = this.expected()
    const dbStatus = await this.db.status()
    if (!dbStatus.installed) throw new Error('PostgreSQL is not installed')
    if (!dbStatus.running) throw new Error('PostgreSQL is not running')

    const registered = await this.rows("SELECT to_regclass('memory.schema_version') AS reg")
    if (registered.length && registered[0].reg !== null) {
      const versions = await this.rows('SELECT embedding_dimensions FROM memory.schema_version ORDER BY version DESC LIMIT 1')
      if (versions.length && Number(versions[0].embedding_dimensions) !== expected.dimensions) {
        return await this.status()
      }
    }

    try {
      await this.db.query('admin', buildSchemaSql(expected.dimensions))
      this.lastError = null
      return await this.status()
    } catch (error) {
      this.lastError = error instanceof Error ? error.message : String(error)
      throw error
    }
  }
}
